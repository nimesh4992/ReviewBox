/**
 * cluster-metrics.ts — scoring for the ADR 011 §9 bake-off.
 *
 * Scores a candidate clustering against the hand-labelled golden set
 * (`docs/GOLDEN_SET.md`). Pure functions, no I/O, no network.
 *
 * ── Two things here are policy, not preference ──────────────────────────────
 *
 * 1. **False merges are reported separately and weighted heaviest** (D025).
 *    A false split scatters one problem across two cards: annoying, visible,
 *    a human fixes it. A false merge fuses three unrelated engineering problems
 *    into one confident "Payment failures · 47 reviews · Critical": invisible,
 *    and it sends the customer to spend their week on the wrong thing. These
 *    are not two sides of one number and must never be traded off as if they
 *    were, which is why `precision`/`recall` alone are not enough.
 *
 * 2. **Nothing here produces a headline average across language buckets** (D025).
 *    `overall` exists because the slices have to sum to something, and it is
 *    explicitly labelled not-a-headline. Reporting "overall 86%" over a 42%
 *    Hinglish column is the specific failure the founder forbade: for an
 *    India-first product that column is not a detail of the result, it IS the
 *    result.
 *
 * ── What the 2026-08-20 readiness review found, and what changed ────────────
 *
 * Scored against the real 200-review census (english 194 · hinglish 6 ·
 * native-script 0), the previous version of this module failed both policies
 * above by a side door:
 *
 * a. **Empty slices vanished.** `bySlice` only ever contained keys that had at
 *    least one pair, so a corpus with no native-script reviews produced a
 *    three-row report that looked complete. Half the required buckets were
 *    untested and nothing said so. `expectedSliceKeys()` now derives all six
 *    from LANGUAGE_BUCKETS and every one is always present, `empty` ones
 *    included.
 *
 * b. **`safety.weightedErrors` was an unsliced headline in all but name.** It
 *    is the only single number here, it is documented "lower is better", and
 *    on a 97%-English corpus it is ~94% determined by English pairs. Measured:
 *    an engine with English-perfect / Hinglish-catastrophic output scored 207,
 *    while one with perfect Hinglish and mildly sloppy English scored 300 — so
 *    the number ranked the Hinglish failure FIRST, inverting the ranking §9
 *    mandates. It is retained for diagnosis, marked `diagnosticOnly`, and
 *    `compareEngines()` refuses to read it.
 *
 * c. **A big pair count hid a tiny sample.** `cross:english×hinglish` had 1,164
 *    pairs generated by six Hinglish reviews. Pairs are not independent
 *    observations; the limiting arm is. Eligibility now gates on the SMALLER
 *    side of a slice, so that slice is correctly `low-n`.
 */

import type { LanguageBucket } from "./language-bucket";

/**
 * The bucket vocabulary, mirrored from LANGUAGE_BUCKETS.
 *
 * It is mirrored rather than imported because of a hard toolchain corner, not
 * preference: `scripts/eval/score.mjs` loads this module through Node's
 * `--experimental-strip-types`, which cannot resolve `./language-bucket`
 * without a `.ts` extension — while `tsc` rejects that extension outright
 * (`allowImportingTsExtensions` is off, TS5097). A `.ts`→`.ts` **value** import
 * therefore cannot satisfy both. Type-only imports are erased before Node sees
 * them, which is why the type above is safe and the array is not.
 *
 * Mirroring without enforcement would be exactly the drift this module exists
 * to prevent, so both directions are checked at COMPILE time:
 *
 *  - `satisfies` rejects a member that is not a LanguageBucket;
 *  - `_MustCoverEveryBucket` fails to compile if a bucket is added to the union
 *    and not added here.
 *
 * Adding a fourth bucket therefore breaks the build here, on purpose.
 */
const BUCKETS = ["english", "native-script", "hinglish"] as const satisfies readonly LanguageBucket[];

type _MustCoverEveryBucket =
  Exclude<LanguageBucket, (typeof BUCKETS)[number]> extends never ? true : never;
const _bucketsAreExhaustive: _MustCoverEveryBucket = true;
void _bucketsAreExhaustive;

/**
 * A slice is `usable`, `low-n` or `empty`. Only `usable` may decide anything.
 *
 * `low-n` is not a softer `usable`: a slice with three same-issue pairs can
 * print 100% or 0% on one labelling judgement, and a number that swings that
 * far on one human decision cannot carry an engine choice (ADR 011 §10).
 *
 * `aggregate` belongs to `overall` alone. It is never eligible, whatever its
 * numbers look like — that is the D025 rule expressed in the type rather than
 * in a comment somebody can skip.
 */
export type SliceStatus = "usable" | "low-n" | "empty" | "aggregate";

/** A slice needs this many reviews on its SMALLER side to be eligible. */
export const MIN_SLICE_REVIEWS = 10;
/** …and this many pairs. Both must hold. */
export const MIN_SLICE_PAIRS = 30;

/** Slice key for a pair. Cross-bucket keys are sorted so a×b and b×a agree. */
export function sliceKey(a: LanguageBucket, b: LanguageBucket): string {
  if (a === b) return `within:${a}`;
  return `cross:${[a, b].sort().join("×")}`;
}

/**
 * Every slice the bake-off is required to report — all six, derived from the
 * bucket vocabulary rather than from whatever pairs happened to occur.
 *
 * This is the whole point of the 2026-08-20 fix. Building the key set from the
 * data means a corpus with no native-script reviews produces a three-row report
 * that reads as complete, which is how a bake-off certifies English and gets
 * filed as if it had certified everything.
 */
export function expectedSliceKeys(): string[] {
  const keys: string[] = [];
  for (let i = 0; i < BUCKETS.length; i++) {
    for (let j = i; j < BUCKETS.length; j++) keys.push(sliceKey(BUCKETS[i], BUCKETS[j]));
  }
  return [...new Set(keys)].sort();
}

/** Which buckets a slice key covers. `within:x` → [x]; `cross:a×b` → [a, b]. */
export function bucketsInSlice(key: string): LanguageBucket[] {
  const [kind, rest] = key.split(":");
  const parts = kind === "within" ? [rest] : rest.split("×");
  return parts.filter((p): p is LanguageBucket =>
    (BUCKETS as readonly string[]).includes(p));
}

/** One labelled review from the golden set. `issueId` is the human's grouping key. */
export interface GoldReview {
  id: string;
  issueId: string;
  bucket: LanguageBucket;
}

/** One engine output. `issueId: null` means "the engine declined to attach it". */
export interface PredictedReview {
  id: string;
  issueId: string | null;
}

export interface PairCounts {
  /** Same issue in gold, same cluster in prediction. */
  truePositive: number;
  /** Different issues in gold, same cluster in prediction — THE DANGEROUS ONE. */
  falseMerge: number;
  /** Same issue in gold, different clusters in prediction. */
  falseSplit: number;
  /** Different in both — correctly kept apart. */
  trueNegative: number;
}

export interface SliceScore extends PairCounts {
  precision: number | null;
  recall: number | null;
  f1: number | null;
  pairs: number;
  /** Buckets this slice covers. `within:x` → 1; `cross:a×b` → 2. */
  buckets: LanguageBucket[];
  /** Labelled reviews per bucket that contributed to this slice. */
  reviewsByBucket: Record<string, number>;
  /**
   * The SMALLER arm of the slice — what actually bounds its power.
   *
   * `cross:english×hinglish` on the real census has 1,164 pairs and looks
   * well-powered; those pairs are generated by 6 Hinglish reviews, each
   * appearing in ~194 of them. Pairs are not independent observations. Gating
   * on the limiting arm is what stops a big pair count from laundering a tiny
   * sample into an eligible-looking result.
   */
  limitingReviews: number;
  /** All distinct labelled reviews touching this slice. Reporting only. */
  distinctReviews: number;
  status: SliceStatus;
  /** Only `usable` slices may inform the ADR §10 recommendation. */
  eligible: boolean;
  /** Plain-English reason when `eligible` is false. */
  ineligibleReason: string | null;
  /** Per-slice weighted errors. THIS is the comparable safety number. */
  weightedErrors: number;
}

export interface ClusterShape {
  goldIssues: number;
  predictedClusters: number;
  /** Predicted clusters containing reviews from more than one gold issue. */
  contaminatedClusters: number;
  /** Gold issues whose reviews are spread across more than one predicted cluster. */
  fragmentedGoldIssues: number;
}

export interface DiscoveryScore {
  goldIssues: number;
  /** Gold issues matched by some predicted cluster at the given coverage + purity. */
  discovered: number;
  rate: number | null;
  coverageThreshold: number;
  purityThreshold: number;
}

/**
 * Which slices are allowed to decide, and which are not.
 *
 * ADR 011 §10 is filled in from `eligible` alone. A run where `eligible` is
 * empty cannot produce a recommendation at all — that is a legitimate result
 * of a bake-off and must be recorded as one, not rounded up to the English
 * number that happened to be well-powered.
 */
export interface RecommendationBasis {
  /** Slice keys with enough evidence to decide. */
  eligible: string[];
  /** Everything else, with the reason it cannot decide. */
  excluded: Array<{ slice: string; status: SliceStatus; reason: string }>;
  /** True when no slice qualifies — §10 stays unanswered. */
  insufficient: boolean;
  /** Buckets with zero labelled reviews. Untested, not passed. */
  untestedBuckets: LanguageBucket[];
}

export interface ClusterScoreReport {
  /** NOT a headline, and NOT a decision criterion. See the module header. */
  overall: SliceScore;
  /** Always all six keys from `expectedSliceKeys()`, `empty` ones included. */
  bySlice: Record<string, SliceScore>;
  recommendation: RecommendationBasis;
  shape: ClusterShape;
  discovery: DiscoveryScore;
  /** Reviews the engine declined to attach. A gap, not a lie (ADR 011 §6). */
  unassigned: number;
  /** Gold reviews with no corresponding prediction — a harness problem, not a model one. */
  missingPredictions: number;
  safety: {
    falseMergeWeight: number;
    /**
     * falseMerge × weight + falseSplit, across every pair.
     *
     * **Diagnostic only — never an engine-selection criterion.** On the real
     * census 94% of pairs are English, so this number is ~94% an English
     * number. Measured on 2026-08-20: it scored an English-perfect /
     * Hinglish-catastrophic engine at 207 and a Hinglish-perfect /
     * English-sloppy engine at 300, ranking the Hinglish failure first —
     * the inversion ADR 011 §9 exists to prevent. Use `bySlice[k].weightedErrors`.
     */
    weightedErrors: number;
    /** Always true. Present so a consumer cannot claim it did not know. */
    diagnosticOnly: true;
  };
}

/**
 * How much worse a false merge is than a false split, for the single
 * comparison number. Raw counts stay authoritative — this is a reporting aid.
 */
export const DEFAULT_FALSE_MERGE_WEIGHT = 3;

const EMPTY_COUNTS = (): PairCounts => ({
  truePositive: 0,
  falseMerge: 0,
  falseSplit: 0,
  trueNegative: 0,
});

function finalise(
  counts: PairCounts,
  key: string,
  reviewsByBucket: Record<string, number>,
  falseMergeWeight: number,
): SliceScore {
  const { truePositive: tp, falseMerge: fm, falseSplit: fs, trueNegative: tn } = counts;
  const precision = tp + fm > 0 ? tp / (tp + fm) : null;
  const recall = tp + fs > 0 ? tp / (tp + fs) : null;
  const f1 =
    precision !== null && recall !== null && precision + recall > 0
      ? (2 * precision * recall) / (precision + recall)
      : null;
  const pairs = tp + fm + fs + tn;

  const buckets = bucketsInSlice(key);
  const arms = buckets.map((b) => reviewsByBucket[b] ?? 0);
  const limitingReviews = arms.length ? Math.min(...arms) : 0;
  const distinctReviews =
    buckets.length > 1 ? arms.reduce((a, b) => a + b, 0) : (arms[0] ?? 0);

  let status: SliceStatus;
  let ineligibleReason: string | null;
  if (pairs === 0) {
    status = "empty";
    const bare = buckets.filter((b) => (reviewsByBucket[b] ?? 0) === 0);
    ineligibleReason = bare.length
      ? `no labelled reviews in ${bare.join(" or ")}`
      : "no pairs in this slice";
  } else if (limitingReviews < MIN_SLICE_REVIEWS || pairs < MIN_SLICE_PAIRS) {
    status = "low-n";
    const why = [
      limitingReviews < MIN_SLICE_REVIEWS
        ? `${limitingReviews} review(s) on the smaller side, floor ${MIN_SLICE_REVIEWS}`
        : null,
      pairs < MIN_SLICE_PAIRS ? `${pairs} pair(s), floor ${MIN_SLICE_PAIRS}` : null,
    ].filter(Boolean);
    ineligibleReason = why.join("; ");
  } else {
    status = "usable";
    ineligibleReason = null;
  }

  return {
    ...counts,
    precision,
    recall,
    f1,
    pairs,
    buckets,
    reviewsByBucket,
    limitingReviews,
    distinctReviews,
    status,
    eligible: status === "usable",
    ineligibleReason,
    weightedErrors: fm * falseMergeWeight + fs,
  };
}

/**
 * Score a predicted clustering against the golden set.
 *
 * Pairwise over every unordered pair of labelled reviews. A review the engine
 * declined to attach (`issueId: null`) is never "same cluster" as anything, so
 * declining costs recall and never costs precision — which is the incentive
 * ADR 011 §6 intends ("when uncertain, separate rather than merge").
 */
export function scoreClustering(
  gold: readonly GoldReview[],
  predicted: readonly PredictedReview[],
  options: { falseMergeWeight?: number; coverageThreshold?: number; purityThreshold?: number } = {},
): ClusterScoreReport {
  const falseMergeWeight = options.falseMergeWeight ?? DEFAULT_FALSE_MERGE_WEIGHT;
  const coverageThreshold = options.coverageThreshold ?? 0.6;
  const purityThreshold = options.purityThreshold ?? 0.8;

  const predictionById = new Map(predicted.map((p) => [p.id, p.issueId]));
  const scored = gold.filter((g) => predictionById.has(g.id));
  const missingPredictions = gold.length - scored.length;

  const overall = EMPTY_COUNTS();
  const bySliceCounts: Record<string, PairCounts> = {};

  for (let i = 0; i < scored.length; i++) {
    for (let j = i + 1; j < scored.length; j++) {
      const a = scored[i];
      const b = scored[j];
      const goldSame = a.issueId === b.issueId;
      const predA = predictionById.get(a.id) ?? null;
      const predB = predictionById.get(b.id) ?? null;
      const predSame = predA !== null && predA === predB;

      const key = sliceKey(a.bucket, b.bucket);
      bySliceCounts[key] ??= EMPTY_COUNTS();
      const bucketCounts = bySliceCounts[key];

      let field: keyof PairCounts;
      if (goldSame && predSame) field = "truePositive";
      else if (!goldSame && predSame) field = "falseMerge";
      else if (goldSame && !predSame) field = "falseSplit";
      else field = "trueNegative";

      overall[field]++;
      bucketCounts[field]++;
    }
  }

  // How many labelled reviews each bucket contributed. Zero is a real answer
  // and must survive into the report — it is what makes a bucket "untested"
  // rather than "passed".
  const reviewCountByBucket: Record<string, number> = {};
  for (const bucket of BUCKETS) reviewCountByBucket[bucket] = 0;
  for (const g of scored) {
    reviewCountByBucket[g.bucket] = (reviewCountByBucket[g.bucket] ?? 0) + 1;
  }

  // EVERY expected slice, not just the ones that happened to have pairs.
  const bySlice: Record<string, SliceScore> = {};
  for (const key of expectedSliceKeys()) {
    bySlice[key] = finalise(
      bySliceCounts[key] ?? EMPTY_COUNTS(),
      key,
      reviewCountByBucket,
      falseMergeWeight,
    );
  }

  const eligible = Object.keys(bySlice).filter((k) => bySlice[k].eligible).sort();
  const excluded = Object.keys(bySlice)
    .filter((k) => !bySlice[k].eligible)
    .sort()
    .map((slice) => ({
      slice,
      status: bySlice[slice].status,
      reason: bySlice[slice].ineligibleReason ?? "not eligible",
    }));

  // `overall` is deliberately NOT a slice. It is given its own status so it can
  // never be picked up as one: a reader scanning for eligible slices, and
  // `compareEngines()` below, both skip it by construction rather than by
  // remembering to. Reporting "overall 86%" over a 42% Hinglish column is the
  // exact failure D025 forbids.
  const overallScore: SliceScore = {
    ...finalise(overall, "aggregate:overall", reviewCountByBucket, falseMergeWeight),
    buckets: [],
    limitingReviews: 0,
    distinctReviews: scored.length,
    status: "aggregate",
    eligible: false,
    ineligibleReason:
      "aggregate across every bucket — not a headline and not a decision criterion (D025)",
  };

  return {
    overall: overallScore,
    bySlice,
    recommendation: {
      eligible,
      excluded,
      insufficient: eligible.length === 0,
      untestedBuckets: BUCKETS.filter((b) => (reviewCountByBucket[b] ?? 0) === 0),
    },
    shape: describeShape(scored, predictionById),
    discovery: scoreDiscovery(scored, predictionById, coverageThreshold, purityThreshold),
    unassigned: scored.filter((g) => predictionById.get(g.id) === null).length,
    missingPredictions,
    safety: {
      falseMergeWeight,
      weightedErrors: overall.falseMerge * falseMergeWeight + overall.falseSplit,
      diagnosticOnly: true,
    },
  };
}

function groupBy<T, K>(items: readonly T[], key: (item: T) => K): Map<K, T[]> {
  const map = new Map<K, T[]>();
  for (const item of items) {
    const k = key(item);
    const existing = map.get(k);
    if (existing) existing.push(item);
    else map.set(k, [item]);
  }
  return map;
}

function describeShape(
  gold: readonly GoldReview[],
  predictionById: ReadonlyMap<string, string | null>,
): ClusterShape {
  const goldGroups = groupBy(gold, (g) => g.issueId);
  const attached = gold.filter((g) => predictionById.get(g.id) !== null);
  const predictedGroups = groupBy(attached, (g) => predictionById.get(g.id) as string);

  let contaminatedClusters = 0;
  for (const members of predictedGroups.values()) {
    if (new Set(members.map((m) => m.issueId)).size > 1) contaminatedClusters++;
  }

  let fragmentedGoldIssues = 0;
  for (const members of goldGroups.values()) {
    const clusters = new Set(members.map((m) => predictionById.get(m.id)));
    if (clusters.size > 1) fragmentedGoldIssues++;
  }

  return {
    goldIssues: goldGroups.size,
    predictedClusters: predictedGroups.size,
    contaminatedClusters,
    fragmentedGoldIssues,
  };
}

/**
 * "Did it discover the right Issues?" — a different question from "did it
 * classify this review?", and the one the product claim rests on.
 *
 * A gold issue counts as discovered when some predicted cluster both covers
 * enough of it (coverage) and is not mostly other things (purity).
 */
function scoreDiscovery(
  gold: readonly GoldReview[],
  predictionById: ReadonlyMap<string, string | null>,
  coverageThreshold: number,
  purityThreshold: number,
): DiscoveryScore {
  const goldGroups = groupBy(gold, (g) => g.issueId);
  const attached = gold.filter((g) => predictionById.get(g.id) !== null);
  const predictedGroups = groupBy(attached, (g) => predictionById.get(g.id) as string);

  let discovered = 0;
  for (const [issueId, members] of goldGroups) {
    for (const clusterMembers of predictedGroups.values()) {
      const overlap = clusterMembers.filter((m) => m.issueId === issueId).length;
      const coverage = overlap / members.length;
      const purity = overlap / clusterMembers.length;
      if (coverage >= coverageThreshold && purity >= purityThreshold) {
        discovered++;
        break;
      }
    }
  }

  return {
    goldIssues: goldGroups.size,
    discovered,
    rate: goldGroups.size > 0 ? discovered / goldGroups.size : null,
    coverageThreshold,
    purityThreshold,
  };
}

/** One engine's scored run, for `compareEngines`. */
export interface EngineEntry {
  name: string;
  report: ClusterScoreReport;
}

export interface SliceVerdict {
  slice: string;
  /** Best first, by per-slice weighted errors. */
  ranking: Array<{ name: string; weightedErrors: number; f1: number | null }>;
  /** Every engine tied for best in this slice. */
  best: string[];
}

export interface ComparisonVerdict {
  /** Only slices eligible in EVERY engine's report. */
  perSlice: SliceVerdict[];
  /**
   * The engine that leads every eligible slice — which is NOT the same as the
   * winner, and must never be reported as one when `bucketsMissing` is
   * non-empty. See the note on `winner`.
   */
  leader: string | null;
  /**
   * `leader`, but only when every language bucket had a say.
   *
   * Excluding a low-n slice stops it deciding — it must not make the decision
   * *easier*. On the real census English is the only eligible slice, so an
   * engine that is perfect in English and catastrophic in Hinglish leads
   * everything that is allowed to count, and a naive winner would be exactly
   * the answer ADR 011 §9 was written to prevent. A recommendation therefore
   * requires coverage of every bucket, not merely the absence of contradiction.
   */
  winner: string | null;
  /** Buckets represented by at least one eligible slice. */
  bucketsCovered: LanguageBucket[];
  /** Buckets with no eligible slice. Non-empty ⇒ `winner` is null. */
  bucketsMissing: LanguageBucket[];
  reason: string;
  /** True when different engines win different slices. */
  conflicted: boolean;
  /** Slices that could not take part, with why. */
  blockedBy: Array<{ slice: string; status: SliceStatus; reason: string }>;
  untestedBuckets: LanguageBucket[];
}

/**
 * Pick a winner from per-slice evidence — or decline to.
 *
 * **This function never reads `report.safety.weightedErrors`, `report.overall`,
 * `report.discovery` or `report.shape`.** All four are unsliced, and on a
 * corpus that is 97% one language an unsliced number is that language's number
 * wearing a global label. Measured on 2026-08-20: ranking by the global
 * weighted-error figure put an engine with total Hinglish failure AHEAD of one
 * with perfect Hinglish. So the input to a recommendation is `bySlice`,
 * restricted to slices that are `usable` in every engine being compared.
 *
 * Declining is a real outcome. `winner: null` with `conflicted: true` means the
 * engines genuinely disagree by language and a human must choose knowing that;
 * `winner: null` with an empty `perSlice` means the corpus could not answer the
 * question at all. Neither may be rounded up to whichever number looked best.
 */
export function compareEngines(entries: readonly EngineEntry[]): ComparisonVerdict {
  const untestedBuckets = [
    ...new Set(entries.flatMap((e) => e.report.recommendation.untestedBuckets)),
  ];

  if (entries.length < 2) {
    return {
      perSlice: [],
      leader: null,
      winner: null,
      bucketsCovered: [],
      bucketsMissing: [...BUCKETS],
      reason: "needs at least two engines to compare",
      conflicted: false,
      blockedBy: [],
      untestedBuckets,
    };
  }

  // A slice may only decide if every engine has enough evidence in it.
  const decidable = expectedSliceKeys().filter((key) =>
    entries.every((e) => e.report.bySlice[key]?.eligible),
  );
  const blockedBy = expectedSliceKeys()
    .filter((key) => !decidable.includes(key))
    .map((slice) => {
      const worst = entries
        .map((e) => e.report.bySlice[slice])
        .find((sc) => sc && !sc.eligible);
      return {
        slice,
        status: worst?.status ?? ("empty" as SliceStatus),
        reason: worst?.ineligibleReason ?? "not eligible in at least one engine",
      };
    });

  const perSlice: SliceVerdict[] = decidable.map((slice) => {
    const ranking = entries
      .map((e) => ({
        name: e.name,
        weightedErrors: e.report.bySlice[slice].weightedErrors,
        f1: e.report.bySlice[slice].f1,
      }))
      .sort((a, b) => a.weightedErrors - b.weightedErrors);
    const bestScore = ranking[0].weightedErrors;
    return { slice, ranking, best: ranking.filter((r) => r.weightedErrors === bestScore).map((r) => r.name) };
  });

  const bucketsCovered = BUCKETS.filter((b) =>
    decidable.some((key) => bucketsInSlice(key).includes(b)));
  const bucketsMissing = BUCKETS.filter((b) => !bucketsCovered.includes(b));

  if (!perSlice.length) {
    return {
      perSlice,
      leader: null,
      winner: null,
      bucketsCovered,
      bucketsMissing,
      reason:
        "no slice has enough evidence in every engine — this corpus cannot decide ADR 011 §10",
      conflicted: false,
      blockedBy,
      untestedBuckets,
    };
  }

  // An engine leads only by being best (or tied-best) in every deciding slice.
  const leaders = entries
    .map((e) => e.name)
    .filter((name) => perSlice.every((v) => v.best.includes(name)));
  const leader = leaders.length === 1 ? leaders[0] : null;

  if (leaders.length > 1) {
    return {
      perSlice,
      leader: null,
      winner: null,
      bucketsCovered,
      bucketsMissing,
      reason: `tied across every eligible slice: ${leaders.join(", ")}`,
      conflicted: false,
      blockedBy,
      untestedBuckets,
    };
  }

  if (!leaders.length) {
    return {
      perSlice,
      leader: null,
      winner: null,
      bucketsCovered,
      bucketsMissing,
      reason:
        "engines disagree by language slice — no single winner. A human must choose " +
        "knowing which language each engine fails, per ADR 011 §9",
      conflicted: true,
      blockedBy,
      untestedBuckets,
    };
  }

  // One engine leads. Whether that is a recommendation depends on coverage.
  if (bucketsMissing.length) {
    return {
      perSlice,
      leader,
      winner: null,
      bucketsCovered,
      bucketsMissing,
      reason:
        `${leader} leads every eligible slice, but ${bucketsMissing.join(", ")} had no ` +
        "eligible slice at all — so this is a lead in one language, not a recommendation. " +
        "Excluding a weak slice must not make the choice easier (ADR 011 §9)",
      conflicted: false,
      blockedBy,
      untestedBuckets,
    };
  }

  return {
    perSlice,
    leader,
    winner: leader,
    bucketsCovered,
    bucketsMissing,
    reason: `best or tied-best in every eligible slice (${decidable.join(", ")}), ` +
      "with every language bucket represented",
    conflicted: false,
    blockedBy,
    untestedBuckets,
  };
}

function pct(value: number | null): string {
  return value === null ? "  n/a" : `${(value * 100).toFixed(1)}%`;
}

/**
 * Render a report for the terminal.
 *
 * Every one of the six slices is printed, always, including the ones with no
 * examples — an absent row reads as "not applicable here" when it actually
 * means "never tested". The eligibility footer, not the numbers, is what
 * ADR 011 §10 is filled in from.
 */
export function formatScoreReport(report: ClusterScoreReport, label: string): string {
  const lines: string[] = [];
  lines.push(`\n═══ ${label} ═══`);
  lines.push("");
  lines.push("  slice                            n   pairs  precision   recall      F1  merges  splits   wErr");
  lines.push("  " + "─".repeat(94));

  for (const key of expectedSliceKeys()) {
    const s = report.bySlice[key];
    if (!s || s.status === "empty") {
      const why = s?.ineligibleReason ? ` (${s.ineligibleReason})` : "";
      lines.push("  " + key.padEnd(30) + `N/A — 0 examples${why}`);
      continue;
    }
    lines.push(
      "  " +
        key.padEnd(30) +
        String(s.limitingReviews).padStart(4) +
        String(s.pairs).padStart(8) +
        pct(s.precision).padStart(11) +
        pct(s.recall).padStart(9) +
        pct(s.f1).padStart(8) +
        String(s.falseMerge).padStart(8) +
        String(s.falseSplit).padStart(8) +
        String(s.weightedErrors).padStart(7),
    );
    if (s.status === "low-n") {
      lines.push(`  ${" ".repeat(30)}low-n / exploratory — ${s.ineligibleReason}`);
    }
  }

  lines.push("");
  lines.push(`  Issue discovery:  ${report.discovery.discovered}/${report.discovery.goldIssues} ` +
    `(coverage ≥${report.discovery.coverageThreshold}, purity ≥${report.discovery.purityThreshold})`);
  lines.push(`  Clusters:         ${report.shape.predictedClusters} predicted vs ${report.shape.goldIssues} real · ` +
    `${report.shape.contaminatedClusters} contaminated · ${report.shape.fragmentedGoldIssues} fragmented`);
  lines.push(`  Unassigned:       ${report.unassigned} reviews (a gap, not a lie — ADR 011 §6)`);
  if (report.missingPredictions > 0) {
    lines.push(`  ⚠ ${report.missingPredictions} labelled reviews had no prediction — harness problem, not a model one`);
  }

  lines.push("");
  lines.push("  ── What may decide ADR 011 §10 ──");
  const basis = report.recommendation;
  lines.push(`  Eligible slices:  ${basis.eligible.length ? basis.eligible.join(", ") : "NONE"}`);
  for (const item of basis.excluded) {
    lines.push(`    excluded: ${item.slice.padEnd(28)} ${item.status} — ${item.reason}`);
  }
  if (basis.untestedBuckets.length) {
    lines.push(
      `  ⚠ UNTESTED buckets: ${basis.untestedBuckets.join(", ")} — untested is NOT passed.`,
    );
  }
  if (basis.insufficient) {
    lines.push("  ⚠ No slice qualifies. This run cannot produce a §10 recommendation.");
  }

  lines.push("");
  lines.push("  ── Diagnostic only — NOT engine-selection criteria (D025) ──");
  lines.push(`  overall F1:       ${pct(report.overall.f1)} — NOT a headline, NOT a decision`);
  lines.push("                    criterion. It is an aggregate across every bucket.");
  lines.push(`  weightedErrors:   ${report.safety.weightedErrors} ` +
    `(merges ×${report.safety.falseMergeWeight} + splits), unsliced. On a corpus`);
  lines.push("                    dominated by one language this is that language's number.");
  lines.push("                    Compare engines with compareEngines(), never with this.");
  return lines.join("\n");
}
